function initialLanguage(): Language {
  if (typeof localStorage === 'undefined') return 'en';
  return (localStorage.getItem('language') as Language | null) || 'en';
}

export const language = writable<Language>(initialLanguage());

export type TranslationKey = keyof typeof dictionaries.en;

export const translator = derived(language, ($language) => {
  return (key: TranslationKey): string => {
    return dictionaries[$language][key] || dictionaries.en[key];
  };
});

language.subscribe((value) => {
  if (typeof localStorage !== 'undefined') localStorage.setItem('language', value);
});

export function t(key: keyof typeof dictionaries.en): string {
  let current: Language = 'en';
  language.subscribe((value) => current = value)();
  return dictionaries[current][key] || dictionaries.en[key];
}
